"""Generate module/_contract_catalog.py from the pinned kefer-contracts.

The Python sidecar must not keep its own copy of shared catalogs, but it must
also run without kefer-contracts installed (offline, inside the PyInstaller
sidecar). The generated module is plain Python data, derived only from the
pinned contracts; `--check` fails when it is out of date.

    python -m devtools.sync_contracts          # regenerate
    python -m devtools.sync_contracts --check  # verify (also run by the tests)
"""

from __future__ import annotations

import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "module" / "_contract_catalog.py"


def render(contracts_dir: Path) -> str:
    manifest = json.loads((contracts_dir / "manifest.json").read_text(encoding="utf-8"))
    catalog = json.loads((contracts_dir / "catalogs/aspects.json").read_text(encoding="utf-8"))
    conventions = json.loads((contracts_dir / "conventions.json").read_text(encoding="utf-8"))
    rows = tuple(
        (a["id"], a["label"], a["angle"], a["default_orb"]) for a in catalog["aspects"]
    )
    return (
        '"""GENERATED by devtools/sync_contracts.py from kefer-contracts '
        f'{manifest["version"]} — do not edit."""\n\n'
        f"KEFER_CONTRACTS_VERSION = {manifest['version']!r}\n"
        f"ASPECT_CATALOG_VERSION = {catalog['catalog_version']!r}\n"
        f"CALCULATION_CONVENTION = {conventions['default']!r}\n\n"
        "# (id, label, angle_deg, default_orb_deg) in catalog order\n"
        f"ASPECT_CATALOG = {pprint.pformat(rows, width=96)}\n\n"
        f"ASPECT_ALIASES = {pprint.pformat(dict(catalog['aliases']), width=96)}\n"
    )


def main() -> int:
    sys.path.insert(0, str(ROOT))
    from tests.contracts_location import contracts_dir  # verifies version + hashes

    content = render(contracts_dir())
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("module/_contract_catalog.py is out of date; run python -m devtools.sync_contracts")
            return 1
        print("module/_contract_catalog.py is up to date")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
