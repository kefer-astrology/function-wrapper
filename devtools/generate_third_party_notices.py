def _pins() -> list[tuple[str, str]]:
    pins = {}
    for lock in LOCKS:
        for line in lock.read_text(encoding="utf-8").splitlines():
            match = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line)
            if match:
                pins[match.group(1).lower()] = (match.group(1), match.group(2))
    return sorted(pins.values(), key=lambda pin: pin[0].lower())


def _license(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    declared = (meta.get("License") or "").strip()
    if declared and "\n" not in declared and len(declared) <= 60:
        return declared
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    if classifiers:
        return " / ".join(classifiers)
    if declared:
        return declared.splitlines()[0][:60] + " (see package)"
    return "UNKNOWN"


def _homepage(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    for entry in meta.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in {"source", "source code", "repository", "homepage", "code"}:
            return url.strip()
    return (meta.get("Home-page") or "").strip()


def render() -> str:
    rows = []
    for name, pinned in _pins():
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            rows.append(f"| {name} | {pinned} | NOT INSTALLED - regenerate in an api.txt environment | |")
            continue
        if dist.version != pinned:
            raise SystemExit(f"{name}: installed {dist.version}, locked {pinned}; install requirements/api.txt first")
        rows.append(f"| {name} | {pinned} | {_license(dist)} | {_homepage(dist)} |")
    table = ["## Python packages (requirements/base.txt + api.txt)", "", "| Package | Version | License | Project |", "|---|---|---|---|", *rows, ""]
    return HEADER + "\n" + "\n".join(table)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("THIRD_PARTY_NOTICES.md is out of date; run python -m devtools.generate_third_party_notices")
            return 1
        print("THIRD_PARTY_NOTICES.md is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
