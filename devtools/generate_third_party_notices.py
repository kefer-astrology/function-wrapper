"""Generate THIRD_PARTY_NOTICES.md for the Kefer Python sidecar.

Lists every package pinned in requirements/base.txt and requirements/api.txt
(the runtime locks of the bundled sidecar) with the license declared in its installed
metadata, plus curated data/asset attributions.

Run inside an environment where requirements/api.txt (which includes base) is installed:

    python -m devtools.generate_third_party_notices          # rewrite
    python -m devtools.generate_third_party_notices --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCKS = (ROOT / "requirements" / "base.txt", ROOT / "requirements" / "api.txt")
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"

